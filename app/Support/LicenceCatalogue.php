<?php

declare(strict_types=1);

namespace App\Support;

use App\Data\LicenceTypeData;
use App\Enums\LicenceDocument;
use App\Enums\LicenceProvider;
use App\Enums\LicenceRole;
use App\Models\Currency;
use App\Models\DriverLicence;
use Illuminate\Support\Collection;
use InvalidArgumentException;

/**
 * The Licence Types of each Licence Provider and the forms they publish, as listed in config/licences.php, limited to
 * the types this instance handles (LICENCE_TYPES), and the price of a renewal outside enrollment.
 */
final class LicenceCatalogue
{
    /**
     * The providers with at least one active Licence Type.
     *
     * @return array<int, LicenceProvider>
     */
    public static function providers(): array
    {
        return array_values(array_filter(
            LicenceProvider::cases(),
            fn (LicenceProvider $provider) => self::types($provider)->isNotEmpty(),
        ));
    }

    /**
     * The providers a championship can name: the ones offered, plus the one already chosen.
     *
     * @return array<int, LicenceProvider>
     */
    public static function selectableProviders(?LicenceProvider $current = null): array
    {
        return array_values(array_filter(
            LicenceProvider::cases(),
            fn (LicenceProvider $provider) => $provider === $current || in_array($provider, self::providers(), true),
        ));
    }

    /**
     * The Licence Types of the provider the instance handles, in the order they are listed. Inactive ones only when
     * asked for.
     *
     * @return Collection<int, LicenceTypeData>
     */
    public static function types(LicenceProvider $provider, bool $withInactive = false): Collection
    {
        return self::listed($provider)
            ->filter(fn (LicenceTypeData $type) => self::isEnabled($provider, $type->code))
            ->filter(fn (LicenceTypeData $type) => $withInactive || $type->active)
            ->values();
    }

    /**
     * The Licence Type with the given code, also when inactive or not handled by the instance, so existing Licences
     * keep their name.
     */
    public static function find(?LicenceProvider $provider, ?string $code): ?LicenceTypeData
    {
        if ($provider === null || $code === null) {
            return null;
        }

        return self::listed($provider)->firstWhere('code', $code);
    }

    /**
     * Whether the instance handles the Licence Type: every type when LICENCE_TYPES is empty.
     */
    public static function isEnabled(LicenceProvider $provider, string $code): bool
    {
        $enabled = self::enabledTypes();

        return $enabled === [] || in_array("{$provider->value}.{$code}", $enabled, true);
    }

    /**
     * Whether the instance handles only some Licence Types.
     */
    public static function restrictsTypes(): bool
    {
        return self::enabledTypes() !== [];
    }

    /**
     * The link to the form published by the provider, when it replaces the pre-filled one generated by the platform.
     */
    public static function formUrl(?LicenceProvider $provider, LicenceDocument $document): ?string
    {
        if ($provider === null) {
            return null;
        }

        /** @var ?string */
        return config("licences.forms.{$provider->value}.{$document->value}");
    }

    /**
     * The Licence Types that can be picked for the provider: the active ones, plus the one already picked while the
     * instance handles it.
     *
     * @return Collection<int, LicenceTypeData>
     */
    public static function selectableTypes(LicenceProvider $provider, ?string $current = null): Collection
    {
        return self::types($provider, withInactive: true)
            ->filter(fn (LicenceTypeData $type) => $type->active || $type->code === $current)
            ->values();
    }

    /**
     * The codes of the Licence Types that can be picked for the provider.
     *
     * @return array<int, string>
     */
    public static function selectableCodes(LicenceProvider $provider, ?string $current = null): array
    {
        return self::selectableTypes($provider, $current)->pluck('code')->all();
    }

    /**
     * The renewal price in cents when it is a single amount, null when it is a range or not set.
     *
     * @throws InvalidArgumentException when LICENCE_RENEWAL_PRICE cannot be read
     */
    public static function fixedRenewalPrice(): ?int
    {
        $range = self::renewalPriceRange();

        return $range !== null && $range[0] === $range[1] ? $range[0] : null;
    }

    /**
     * The renewal price as shown to people, e.g. "€50.00" or "€50.00 – €80.00", null when not set.
     *
     * @throws InvalidArgumentException when LICENCE_RENEWAL_PRICE cannot be read
     */
    public static function renewalPriceLabel(): ?string
    {
        $range = self::renewalPriceRange();

        if ($range === null) {
            return null;
        }

        [$min, $max] = $range;

        return $min === $max
            ? Currency::EUR->format($min)
            : Currency::EUR->format($min).' – '.Currency::EUR->format($max);
    }

    /**
     * Every Licence Type listed for the provider. A type the instance does not handle is inactive.
     *
     * @return Collection<int, LicenceTypeData>
     */
    private static function listed(LicenceProvider $provider): Collection
    {
        return collect(self::configuredTypes($provider))
            ->map(fn (array $type, string $code) => new LicenceTypeData(
                provider: $provider,
                code: $code,
                name: $type['name'],
                role: $type['role'],
                raceLicenceCategory: $type['race_licence_category'] ?? null,
                active: ($type['active'] ?? true) && self::isEnabled($provider, $code),
            ))
            ->values();
    }

    /**
     * @return array<string, array{name: string, role: LicenceRole, race_licence_category?: ?DriverLicence, active?: bool}>
     */
    private static function configuredTypes(LicenceProvider $provider): array
    {
        /** @var array<string, array{name: string, role: LicenceRole, race_licence_category?: ?DriverLicence, active?: bool}> */
        return config("licences.types.{$provider->value}", []);
    }

    /**
     * The "provider.code" entries of LICENCE_TYPES, empty when every type is handled.
     *
     * @return array<int, string>
     *
     * @throws InvalidArgumentException when an entry names a type that is not listed
     */
    private static function enabledTypes(): array
    {
        /** @var array<int, string> $enabled */
        $enabled = config('licences.enabled_types', []);

        $unknown = array_filter($enabled, function (string $entry) {
            [$provider, $code] = array_pad(explode('.', $entry, 2), 2, '');
            $provider = LicenceProvider::tryFrom($provider);

            return $provider === null || ! array_key_exists($code, self::configuredTypes($provider));
        });

        if ($unknown !== []) {
            throw new InvalidArgumentException('LICENCE_TYPES lists unknown Licence Types: '.implode(', ', $unknown).'.');
        }

        return $enabled;
    }

    /**
     * The lowest and highest renewal price in cents, equal for a single price; null when not set.
     *
     * @return ?array{0: int, 1: int}
     *
     * @throws InvalidArgumentException when LICENCE_RENEWAL_PRICE is not a price like 50 or a range like 50-80
     */
    private static function renewalPriceRange(): ?array
    {
        $price = mb_trim((string) config('licences.renewal_price'));

        if ($price === '') {
            return null;
        }

        if (preg_match('/^(\d+(?:\.\d{1,2})?)(?:\s*-\s*(\d+(?:\.\d{1,2})?))?$/', $price, $matches) !== 1) {
            throw new InvalidArgumentException("LICENCE_RENEWAL_PRICE [{$price}] is not a price like 50 or a range like 50-80.");
        }

        $min = (int) round(((float) $matches[1]) * 100);
        $max = isset($matches[2]) ? (int) round(((float) $matches[2]) * 100) : $min;

        if ($max < $min) {
            throw new InvalidArgumentException("LICENCE_RENEWAL_PRICE [{$price}] starts above where it ends.");
        }

        return [$min, $max];
    }
}
